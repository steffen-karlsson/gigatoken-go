#!/bin/sh
# Generates libpystub.a: stub definitions for the Python C-API symbols
# referenced by the pyo3 objects that survive inside libgigatoken_shim.a.
#
# Why this exists: gigatoken compiles its pyo3/numpy bindings
# unconditionally, and a static library must keep every public symbol of
# its dependency tree, so the (from Go: unreachable) pyo3 code keeps its
# Py_* references alive in the link. Nothing in the Go process ever
# executes that code - these stubs only satisfy the linker.
#
# The stub list is regenerated from the actual archive on every `make
# rust`, so it tracks the pinned gigatoken revision automatically. If a
# future gigatoken feature-gates pyo3 (or a fork does), the stub simply
# becomes an empty archive.
#
# Usage: gen-pystub.sh <libgigatoken_shim.a> <output-dir>
set -eu

lib=$1
outdir=$2
mkdir -p "$outdir"

# Mach-O symbols carry a leading underscore that the C compiler adds
# back; ELF symbols don't.
case "$(uname)" in
    Darwin) strip=1 ;;
    *) strip=0 ;;
esac

{
    echo "/* Auto-generated by rust/gen-pystub.sh - do not edit."
    echo " * Stub definitions for Python C-API symbols referenced by the"
    echo " * unreachable pyo3 code inside libgigatoken_shim.a."
    echo " * Never executed; exists only to satisfy the linker. */"
    nm -u "$lib" 2>/dev/null | awk '{print $NF}' | grep -E '^_+Py[A-Za-z0-9_]+$' | sort -u | while read -r sym; do
        if [ "$strip" = 1 ]; then
            sym=${sym#_}
        fi
        echo "char $sym[1]; /* never executed; satisfies the linker */"
    done
} > "$outdir/pystub.c"

# Respect $CC so cross-builds (see `make static-linux`) stub with the
# target toolchain rather than the host one.
"${CC:-cc}" -c "$outdir/pystub.c" -o "$outdir/pystub.o"
rm -f "$outdir/libpystub.a"
ar crs "$outdir/libpystub.a" "$outdir/pystub.o"
echo "pystub -> $outdir/libpystub.a ($(grep -c 'char.*\[' "$outdir/pystub.c") symbols)"
